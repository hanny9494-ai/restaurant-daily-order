def load_sources():
    domains = {}
    mother_formulas = []
    for path in SOURCE_FILES:
        with path.open("r", encoding="utf-8") as fh:
            data = json.load(fh)
        domains.update(data.get("domains", {}))
        mother_formulas.extend(data.get("mother_formulas", []))
    return domains, {mf["id"] for mf in mother_formulas}


DOMAINS, VALID_MF_IDS = load_sources()


def s(domain: str, index_1_based: int) -> str:
    return DOMAINS[domain][index_1_based - 1]["statement"]


def phn(
    phn_id,
    name_en,
    name_zh,
    domain,
    cross_domains,
    definition,
    observable_cues,
    key_parameters,
    related_mf_ids,
    refs,
    granularity_note,
):
    return {
        "phn_id": phn_id,
        "name_en": name_en,
        "name_zh": name_zh,
        "domain": domain,
        "cross_domains": cross_domains,
        "definition": definition,
        "observable_cues": observable_cues,
        "key_parameters": key_parameters,
        "related_mf_ids": related_mf_ids,
        "example_l0_statements": [s(ref_domain, ref_idx) for ref_domain, ref_idx in refs],
        "granularity_note": granularity_note,
    }


