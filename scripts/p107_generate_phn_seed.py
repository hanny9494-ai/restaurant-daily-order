def validate(phenomena):
    assert 50 <= len(phenomena) <= 80, len(phenomena)
    counts = {}
    seen_ids = set()
    source_statements = {
        item["statement"]
        for items in DOMAINS.values()
        for item in items
    }
    for item in phenomena:
        assert item["phn_id"] not in seen_ids, item["phn_id"]
        seen_ids.add(item["phn_id"])
        counts[item["domain"]] = counts.get(item["domain"], 0) + 1
        for mf_id in item["related_mf_ids"]:
            assert mf_id in VALID_MF_IDS, mf_id
        assert 2 <= len(item["example_l0_statements"]) <= 3, item["phn_id"]
        for stmt in item["example_l0_statements"]:
            assert stmt in source_statements, stmt
    assert len(counts) == 17, counts
    for domain, count in counts.items():
        assert 2 <= count <= 4, (domain, count)


